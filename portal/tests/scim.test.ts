test('SCIM cannot adopt manual members, demote admins, undo manual removal or race duplicate creation',async()=>{
  const f=await fixture()
  await getPool().query("INSERT INTO organisation_members(workspace_id,organisation_id,user_id,role) VALUES($1,$2,$3,'user')",[f.workspace,f.org,f.outsider.userId])
  await assert.rejects(f.call('POST','Users',profile(f.outsider.email)),rejects(409,'uniqueness'))
  const attempts=await Promise.allSettled([f.call('POST','Users',profile(f.person.email)),f.call('POST','Users',profile(f.person.email))])
  assert.equal(attempts.filter(item=>item.status==='fulfilled').length,1)
  const created=(attempts.find(item=>item.status==='fulfilled') as PromiseFulfilledResult<any>).value
  await changeMemberRole(f.owner,f.org,f.person.userId,{role:'admin'})
  await assert.rejects(f.call('DELETE',`Users/${created.body.id}`),rejects(403))
  await assert.rejects(f.call('PATCH',`Users/${created.body.id}`,patch([{op:'replace',path:'active',value:false}])),rejects(403))
  await changeMemberRole(f.owner,f.org,f.person.userId,{role:'user'})
  const before=await f.call('GET',`Users/${created.body.id}`)
  await platform.setMemberStatus(f.owner,f.org,f.person.userId,'suspended')
  const after=await f.call('GET',`Users/${created.body.id}`)
  assert.notEqual(before.etag,after.etag);assert.equal(after.body.active,false)
  await removeMember(f.owner,f.org,f.person.userId)
  await assert.rejects(f.call('PATCH',`Users/${created.body.id}`,patch([{op:'replace',path:'active',value:true}])),rejects(403))
  await assert.rejects(f.call('DELETE',`Users/${created.body.id}`),rejects(403))
  const invitation=await platform.inviteMember(f.owner,f.org,{email:f.person.email,role:'user'})
  const job=(await rows('SELECT id,payload FROM jobs WHERE deduplication_key=$1',[`invitation:${invitation.id}`]))[0]!
  const message=JSON.parse(openSecret(job.payload,`mail:${job.id}`))
  const reference=new URL(message.text.match(/https?:\/\/\S+/)[0]).hash.slice('#token='.length)
  await platform.acceptInvitation(f.person,reference)
  assert.equal((await rows('SELECT scim_user_id FROM organisation_members WHERE organisation_id=$1 AND user_id=$2',[f.org,f.person.userId]))[0]!.scim_user_id,null)
  await assert.rejects(f.call('PATCH',`Users/${created.body.id}`,patch([{op:'replace',path:'active',value:true}])),rejects(403))
})

