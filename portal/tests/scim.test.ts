test('SCIM tokens require admin MFA, remain customer scoped, rotate immediately and do not expose hashes',async()=>{
  const f=await fixture()
  await assert.rejects(rotateScimToken({...f.owner,mfa:false},f.org,{}),error=>(error as any).code==='mfa_required')
  await assert.rejects(scimSettings(f.outsider,f.org),error=>(error as any).code==='not_found')
  for(const header of [undefined,f.issued.token,'Bearer unrelated',`Bearer ${f.issued.token}x`]) await assert.rejects(authenticateScim(f.org,header),rejects(401))
  await assert.rejects(authenticateScim(f.other,`Bearer ${f.issued.token}`),rejects(401))
  await authenticateScim(f.org,`bearer ${f.issued.token}`)
  const settings=JSON.stringify(await scimSettings(f.owner,f.org))
  assert.ok(!settings.includes(f.issued.token));assert.ok(!settings.includes('token_hash'))
  const authorized=await authenticateScim(f.org,`Bearer ${f.issued.token}`)
  const rotated=await rotateScimToken(f.owner,f.org,{})
  await assert.rejects(scimRequest(authorized,'GET',['Users']),rejects(401))
  await assert.rejects(authenticateScim(f.org,`Bearer ${f.issued.token}`),rejects(401))
  await authenticateScim(f.org,`Bearer ${rotated.token}`)
  await revokeScimToken(f.owner,f.org)
  await assert.rejects(authenticateScim(f.org,`Bearer ${rotated.token}`),rejects(401))
  const next=await rotateScimToken(f.owner,f.org,{})
  await getPool().query("UPDATE scim_connections SET token_expires_at=now()-interval '1 second' WHERE organisation_id=$1",[f.org])
  await assert.rejects(authenticateScim(f.org,`Bearer ${next.token}`),rejects(401))
})

