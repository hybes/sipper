test('SCIM CRUD, filters, pagination, versions, discovery and atomic patches follow their declared contract',async()=>{
  const f=await fixture()
  const a=await f.call('POST','Users',profile(f.person.email,{externalId:'Case_Sensitive%'}))
  await f.call('POST','Users',profile(f.outsider.email,{externalId:'second'}))
  await assert.rejects(f.call('GET',`Users/${randomUUID()}`),rejects(404))
  await assert.rejects(f.call('POST','Users',profile(f.person.email)),rejects(409,'uniqueness'))
  const selected=await f.call('GET','Users',undefined,{filter:`userName eq "${f.person.email.toUpperCase()}"`,attributes:'userName,active'})
  assert.equal(selected.body.totalResults,1);assert.deepEqual(Object.keys(selected.body.Resources[0]).sort(),['active','id','schemas','userName'])
  assert.equal((await f.call('GET','Users',undefined,{filter:'externalId eq "Case_Sensitive%"'})).body.totalResults,1)
  assert.equal((await f.call('GET','Users',undefined,{filter:'externalId eq "case_sensitive%"'})).body.totalResults,0)
  assert.equal((await f.call('GET','Users',undefined,{filter:'displayName eq "%"'})).body.totalResults,0)
  assert.equal((await f.call('GET','Users',undefined,{startIndex:2,count:1})).body.Resources.length,1)
  assert.equal((await f.call('GET','Users',undefined,{startIndex:0,count:0})).body.totalResults,2)
  const search=await f.call('POST','Users/.search',{schemas:[SCIM.Search],filter:`id eq "${a.body.id}"`,attributes:['userName']})
  assert.equal(search.body.Resources[0].userName,f.person.email)
  await assert.rejects(f.call('GET','Users',undefined,{filter:'userName pr'}),rejects(400,'invalidFilter'))
  assert.equal((await f.call('GET','ServiceProviderConfig')).body.bulk.supported,false)
  assert.equal((await f.call('GET','Schemas')).body.Resources.length,2)
  assert.equal((await f.call('GET','ResourceTypes/User')).body.endpoint,'/Users')
  const changed=await f.call('PATCH',`Users/${a.body.id}`,patch([{op:'Replace',path:'Active',value:false},{op:'replace',path:'name.givenName',value:'Updated'}]),{},a.etag)
  assert.equal(changed.body.active,false);assert.equal(changed.body.name.givenName,'Updated')
  await assert.rejects(f.call('PUT',`Users/${a.body.id}`,a.body,{},a.etag),rejects(412))
  await assert.rejects(f.call('PATCH',`Users/${a.body.id}`,patch([{op:'replace',path:'active',value:true},{op:'replace',path:'roles',value:[]}]),{},changed.etag),rejects(400,'mutability'))
  assert.equal((await f.call('GET',`Users/${a.body.id}`)).body.active,false)
  await assert.rejects(f.call('PATCH',`Users/${a.body.id}`,patch([{op:'replace',path:'active'}])),rejects(400,'invalidValue'))
  await assert.rejects(f.call('PATCH',`Users/${a.body.id}`,patch([{op:'remove'}])),rejects(400,'noTarget'))
  const merged=await f.call('PATCH',`Users/${a.body.id}`,patch([{op:'replace',path:'name',value:{givenName:'Partial'}},{op:'add',path:'emails',value:[{value:'first@example.invalid',type:'work',primary:true}]}]))
  assert.equal(merged.body.name.familyName,'Person')
  const repeated=await f.call('PATCH',`Users/${a.body.id}`,patch([{op:'add',path:'emails',value:[{value:'first@example.invalid',type:'work',primary:true}]}]))
  assert.equal(repeated.etag,merged.etag);assert.equal(repeated.body.meta.lastModified,merged.body.meta.lastModified)
  const appended=await f.call('PATCH',`Users/${a.body.id}`,patch([{op:'add',value:{emails:[{value:'second@example.invalid',type:'home',primary:true}]}}]))
  assert.equal(appended.body.emails.length,2);assert.equal(appended.body.emails[0].primary,false);assert.equal(appended.body.emails[1].primary,true)
  await assert.rejects(f.call('PUT',`Users/${a.body.id}`,profile('renamed@example.invalid')),rejects(400,'mutability'))
  await assert.rejects(f.call('POST','Users',{...profile('duplicate@example.invalid'),USERNAME:'other@example.invalid'}),rejects(400,'invalidValue'))
  assert.ok(!JSON.stringify(scimFailure(new Error('private-token'))).includes('private-token'))
})

